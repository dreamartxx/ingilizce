import fs from 'node:fs';
const manifest=JSON.parse(fs.readFileSync(new URL('../public/audio/manifest.json',import.meta.url)));
const texts=Object.keys(manifest.clips).sort();
fs.writeFileSync(new URL('../src/recorded-audio.js',import.meta.url),`// Generated by scripts/index-narration.mjs from the shipped audio manifest.\nconst recordings=new Set(${JSON.stringify(texts,null,2)});\nexport const hasRecording=text=>recordings.has(text);\n`);
console.log(`${texts.length} recordings indexed`);
